import { useEffect, useState } from "react";
import { DataError, parseIndex, type SiteIndex } from "./data";
import { Results } from "./Results";

type Load = { state: "loading" } | { state: "error"; message: string } | { state: "ready"; index: SiteIndex };

export function App() {
  const [load, setLoad] = useState<Load>({ state: "loading" });

  useEffect(() => {
    fetch("data/index.json")
      .then((response) => {
        if (!response.ok) throw new DataError(`data/index.json: HTTP ${response.status}`);
        return response.json();
      })
      .then((raw: unknown) => setLoad({ state: "ready", index: parseIndex(raw) }))
      .catch((error: unknown) => setLoad({ state: "error", message: String(error) }));
  }, []);

  return (
    <>
      <header>
        <h1>
          <a href="#/">Crashproof</a>
        </h1>
        <p className="muted">
          Deterministic fault injection against three runtimes for one returns agent. Simulation
          only.
        </p>
      </header>
      {load.state === "loading" && <p className="muted">Loading…</p>}
      {load.state === "error" && (
        <p role="alert" className="error">
          Could not load results: {load.message}. Run <code>make eval</code> and{" "}
          <code>make site</code>.
        </p>
      )}
      {load.state === "ready" && <Results index={load.index} />}
      <footer className="muted">
        Generated by <code>make eval</code> and <code>make site</code>. Every trace replays
        byte-for-byte from its seed.
      </footer>
    </>
  );
}
