from collections.abc import Mapping, Sequence

_RUNTIME_ORDER = ("hardened", "keyed", "naive")
_INVARIANTS = ("I1", "I2", "I3", "I4", "I5", "I6", "I7", "I8", "I9")
_GROUPS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Duplicates (I1, I5)", ("I1", "I5")),
    ("Money (I2)", ("I2",)),
    ("Policy (I3, I4)", ("I3", "I4")),
    ("Audit (I6, I8)", ("I6", "I8")),
    ("Liveness (I7)", ("I7",)),
    ("Replay (I9)", ("I9",)),
)
_HOW_TO_READ = (
    "Each cell counts seeds, not events.",
    "Naive and keyed have no policy engine and no scan timeout, so their I3, I4 and I7 "
    "failures follow from missing components, not only from faults.",
    "I7 for naive and keyed is derived from the runtime's own terminal flag, because "
    "they have no ledger.",
    "I6 and I8 apply to the hardened runtime only (they read its ledger).",
    "All figures are measured by make eval on simulated providers. This is a "
    "simulation, not a claim about real carriers.",
)
_EXAMPLE_COUNT = 3
_START = "<!-- RESULTS:START -->"
_END = "<!-- RESULTS:END -->"


def _cell(value: object) -> str:
    return "n/a" if value is None else str(value)


def _group_cell(counts: Mapping[str, object], invariants: tuple[str, ...]) -> str:
    values = [counts[name] for name in invariants]
    if all(value is None for value in values):
        return "n/a"
    return " + ".join(_cell(value) for value in values)


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    divider = ["---"] * len(header)
    return [_row(header), _row(divider), *(_row(row) for row in rows)]


def _present(summary: Mapping[str, object]) -> list[str]:
    runtimes = summary["runtimes"]
    assert isinstance(runtimes, Mapping)
    return [name for name in _RUNTIME_ORDER if name in runtimes]


def _counts_of(summary: Mapping[str, object], name: str) -> Mapping[str, object]:
    runtimes = summary["runtimes"]
    assert isinstance(runtimes, Mapping)
    counts = runtimes[name]
    assert isinstance(counts, Mapping)
    return counts


def _grouped_table(summary: Mapping[str, object]) -> list[str]:
    header = ["Runtime", "Seeds", *(label for label, _ in _GROUPS), "Violating seeds"]
    rows = []
    for name in _present(summary):
        counts = _counts_of(summary, name)
        rows.append(
            [
                name,
                str(summary["seeds"]),
                *(_group_cell(counts, members) for _, members in _GROUPS),
                _cell(counts["total_violating_seeds"]),
            ]
        )
    return _table(header, rows)


def _invariant_table(summary: Mapping[str, object]) -> list[str]:
    rows = [
        [name, *(_cell(_counts_of(summary, name)[inv]) for inv in _INVARIANTS)]
        for name in _present(summary)
    ]
    return _table(["Runtime", *_INVARIANTS], rows)


def _examples(summary: Mapping[str, object]) -> list[str]:
    failing = summary["failing_seeds"]
    assert isinstance(failing, Mapping)
    lines = []
    for name in _present(summary):
        seeds = sorted(failing[name])[:_EXAMPLE_COUNT]
        shown = ", ".join(str(seed) for seed in seeds) if seeds else "none"
        lines.append(f"- {name}: {shown}")
    return lines


def build_report(
    summary: Mapping[str, object], failures: Sequence[object] | None = None
) -> str:
    lines = [f"## Results (generated by make eval, {summary['seeds']} seeds)", ""]
    lines += _grouped_table(summary)
    lines += ["", "### Seeds with at least one violation, per invariant", ""]
    lines += _invariant_table(summary)
    lines += ["", "### How to read this", ""]
    lines += [f"- {sentence}" for sentence in _HOW_TO_READ]
    if failures is not None:
        lines += ["", "### Failing seed examples", ""]
        lines += _examples(summary)
    return "\n".join(lines) + "\n"


def splice_results(readme_text: str, report_md: str) -> str:
    for marker in (_START, _END):
        found = readme_text.count(marker)
        if found != 1:
            raise ValueError(f"expected exactly one {marker}, found {found}")
    start = readme_text.index(_START)
    end = readme_text.index(_END)
    if start > end:
        raise ValueError("results markers are out of order")
    body = report_md.removesuffix("\n")
    return readme_text[: start + len(_START)] + "\n" + body + "\n" + readme_text[end:]
